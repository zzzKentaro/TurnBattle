        private static void ApplyRenderer(ParticleSystem ps, Material material, int sortingOrder)
        {
            ParticleSystemRenderer renderer = ps.GetComponent<ParticleSystemRenderer>();
            renderer.material = material != null ? material : defaultMaterial;
            renderer.sortingLayerName = "Effect";
            renderer.sortingOrder = sortingOrder;
        }

        private static ParticleSystem.MinMaxGradient GradientAlpha(Color color, float startAlpha, float endAlpha)
        {
            Gradient gradient = new Gradient();
            gradient.SetKeys(
                new[]
                {
                    new GradientColorKey(color, 0f),
                    new GradientColorKey(color, 1f),
                },
                new[]
                {
                    new GradientAlphaKey(startAlpha, 0f),
                    new GradientAlphaKey(endAlpha, 1f),
                });
            return new ParticleSystem.MinMaxGradient(gradient);
        }

        private static Color WithAlpha(Color color, float alpha)
        {
            color.a = alpha;
            return color;
        }

        private static void Save(GameObject root, string fileName)
        {
            string path = $"{OutputFolder}/{fileName}";
            PrefabUtility.SaveAsPrefabAsset(root, path);
            Object.DestroyImmediate(root);
        }

        private static void EnsureFolder()
        {
            EnsureFolder("Assets/MyStuff/Prefab");
            EnsureFolder(OutputFolder);
        }

        private static void EnsureFolder(string path)
        {
            if (AssetDatabase.IsValidFolder(path))
            {
                return;
            }

            string parent = System.IO.Path.GetDirectoryName(path)?.Replace("\\", "/");
            string folder = System.IO.Path.GetFileName(path);
            if (!string.IsNullOrEmpty(parent) && !AssetDatabase.IsValidFolder(parent))
            {
                EnsureFolder(parent);
            }

            AssetDatabase.CreateFolder(parent, folder);
        }

        private static void LoadMaterials()
        {
            defaultMaterial = AssetDatabase.LoadAssetAtPath<Material>(DefaultMaterialPath);
            trailMaterial = AssetDatabase.LoadAssetAtPath<Material>(TrailMaterialPath);
            barrierMaterial = AssetDatabase.LoadAssetAtPath<Material>(BarrierMaterialPath);

            if (defaultMaterial == null)
            {
                defaultMaterial = AssetDatabase.GetBuiltinExtraResource<Material>("Default-Particle.mat");
            }
        }
