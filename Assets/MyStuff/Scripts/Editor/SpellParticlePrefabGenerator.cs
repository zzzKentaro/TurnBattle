        [InitializeOnLoadMethod]
        private static void AutoGenerateIfMissing()
        {
            if (SessionState.GetBool(AutoGenerateSessionKey, false))
            {
                return;
            }

            SessionState.SetBool(AutoGenerateSessionKey, true);
            EditorApplication.delayCall += () =>
            {
                if (!AssetDatabase.IsValidFolder(OutputFolder) || !System.IO.File.Exists($"{OutputFolder}/薪火の魔法.prefab"))
                {
                    GenerateAll();
                }
            };
        }

