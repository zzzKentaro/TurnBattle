        private static GameObject CreateRoot(string name, float duration)
        {
            GameObject root = new GameObject(name);
            ParticleSystem ps = root.AddComponent<ParticleSystem>();
            root.AddComponent<OneShotParticleCallback>();

            ParticleSystem.MainModule main = ps.main;
            main.duration = duration;
            main.loop = false;
            main.playOnAwake = false;
            main.startLifetime = 0.15f;
            main.startSpeed = 0f;
            main.startSize = 0.01f;
            main.startColor = new Color(1f, 1f, 1f, 0f);
            main.simulationSpace = ParticleSystemSimulationSpace.World;
            main.stopAction = ParticleSystemStopAction.Callback;

            ParticleSystem.EmissionModule emission = ps.emission;
            emission.enabled = false;

            return root;
        }

        private static ParticleSystem AddSystem(Transform parent, string name)
        {
            GameObject child = new GameObject(name);
            child.transform.SetParent(parent, false);
            ParticleSystem ps = child.AddComponent<ParticleSystem>();
            ParticleSystem.MainModule main = ps.main;
            main.loop = false;
            main.playOnAwake = false;
            main.simulationSpace = ParticleSystemSimulationSpace.World;
            main.stopAction = ParticleSystemStopAction.None;
            ApplyRenderer(ps, defaultMaterial, 100);
            return ps;
        }

        private static void AddFlameColumn(Transform parent, string name, Color color, short burstCount, float duration, float height)
        {
            ParticleSystem ps = AddSystem(parent, name);
            ParticleSystem.MainModule main = ps.main;
            main.duration = duration;
            main.startLifetime = new ParticleSystem.MinMaxCurve(0.55f, 1.05f);
            main.startSpeed = new ParticleSystem.MinMaxCurve(0.8f, 1.8f);
            main.startSize = new ParticleSystem.MinMaxCurve(0.16f, 0.42f);
            main.startColor = new ParticleSystem.MinMaxGradient(color, WithAlpha(Color.yellow, 0.65f));
            main.gravityModifier = -0.08f;

            ParticleSystem.EmissionModule emission = ps.emission;
            emission.SetBursts(new[] { new ParticleSystem.Burst(0f, burstCount), new ParticleSystem.Burst(0.45f, (short)(burstCount / 2)) });

            ParticleSystem.ShapeModule shape = ps.shape;
            shape.enabled = true;
            shape.shapeType = ParticleSystemShapeType.Cone;
            shape.angle = 18f;
            shape.radius = 0.35f;
            shape.position = new Vector3(0f, -height * 0.25f, 0f);

            ParticleSystem.ColorOverLifetimeModule col = ps.colorOverLifetime;
            col.enabled = true;
            col.color = GradientAlpha(color, 0.95f, 0f);

            ParticleSystem.SizeOverLifetimeModule size = ps.sizeOverLifetime;
            size.enabled = true;
            size.size = new ParticleSystem.MinMaxCurve(1f, AnimationCurve.EaseInOut(0f, 0.5f, 1f, 0.05f));
        }

